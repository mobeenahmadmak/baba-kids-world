// Zero-dependency regression checks. Run: node tests/smoke.cjs
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
const script=html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,'Inline app script is present');
new vm.Script(script[1],{filename:'index.html:inline'});
new vm.Script(sw,{filename:'sw.js'});
assert.match(html,/const KEY='bkw-v1-progress'/,'Existing progress key is preserved');
assert.match(html,/const PIN_KEY='bkw-parent-pin-v4'/,'Parent PIN key is preserved');
for(const term of ['Arfa','Mohid','mathAcademy','SNAPSHOT_KEY','baba-connectivity','Update Now','function restore','function exportData','function recoverSnapshot','recover-snapshot','function startPictureCount','function mathSuggestedTopic','function mathTopicSummary','data-math="smart"','Picture Counting'])assert.ok(html.includes(term),'Missing feature: '+term);
assert.ok(!html.includes("tile('game:math','➗','Math Quest'"),'Removed Math Quest must stay removed');
assert.match(sw,/SKIP_WAITING/);
assert.match(sw,/const cached=\(await caches.match\(request\)\)/,'Navigation uses cached version first');
assert.match(sw,/const CACHE='baba-kids-app-/);
assert.equal(manifest.start_url,'./');
assert.equal(manifest.scope,'./');
assert.equal(manifest.display,'standalone');
assert.ok(fs.existsSync('icon.svg'),'Android SVG icon exists');
const icon=fs.readFileSync('icon.svg','utf8');
assert.match(icon,/<svg[\s\S]*viewBox="0 0 512 512"/);
assert.ok(!icon.includes('⭐'),'Icon uses a reliable vector star instead of a platform-dependent emoji');
assert.ok(manifest.icons.some(i=>i.src==='icon.svg'&&i.purpose.includes('maskable')),'Manifest includes a maskable app icon');
for(const asset of ['./index.html','./manifest.webmanifest','./icon.svg'])assert.ok(sw.includes("'"+asset+"'"),'Missing offline asset: '+asset);
assert.match(html,/function recoverSnapshot\(/);
assert.match(html,/localStorage\.setItem\(KEY,JSON\.stringify\(data\)\)/);

console.log('Baba & Kids World smoke checks passed.');
